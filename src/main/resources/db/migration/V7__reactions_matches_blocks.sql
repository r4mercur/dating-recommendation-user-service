-- Phase 3: reactions (like types), matches and blocks replace the contacts table.
-- V6 is skipped on purpose: an earlier Java migration with that version may exist in local schema histories.

create table reactions
(
    id           bigint generated by default as identity primary key,
    from_user_id bigint      not null references users (id) on delete cascade,
    to_user_id   bigint      not null references users (id) on delete cascade,
    -- reaction types live in the code (ReactionType), new types need no migration
    type         varchar(30) not null,
    message      varchar(500),
    created_at   timestamptz not null default now(),
    unique (from_user_id, to_user_id),
    check (from_user_id <> to_user_id)
);

create index ix_reactions_to_user on reactions (to_user_id, type);
create index ix_reactions_from_user_type_created on reactions (from_user_id, type, created_at);

create table matches
(
    id           bigint generated by default as identity primary key,
    reference_id varchar(36) not null unique default gen_random_uuid()::text,
    -- the pair is stored ordered by user id, so each pair can only have one match
    user_low_id  bigint      not null references users (id) on delete cascade,
    user_high_id bigint      not null references users (id) on delete cascade,
    status       varchar(20) not null,
    created_at   timestamptz not null default now(),
    ended_at     timestamptz,
    ended_by_id  bigint references users (id) on delete set null,
    unique (user_low_id, user_high_id),
    check (user_low_id < user_high_id)
);

create index ix_matches_user_high on matches (user_high_id);

create table blocks
(
    id         bigint generated by default as identity primary key,
    blocker_id bigint      not null references users (id) on delete cascade,
    blocked_id bigint      not null references users (id) on delete cascade,
    created_at timestamptz not null default now(),
    unique (blocker_id, blocked_id),
    check (blocker_id <> blocked_id)
);

create index ix_blocks_blocked on blocks (blocked_id);

-- migrate contacts: ACCEPTED -> LIKE, REJECTED -> PASS, BLOCKED -> block
insert into reactions (from_user_id, to_user_id, type)
select user_id, contact_user_id, case status when 'ACCEPTED' then 'LIKE' else 'PASS' end
from contacts
where status in ('ACCEPTED', 'REJECTED')
  and user_id is not null
  and contact_user_id is not null
  and user_id <> contact_user_id
on conflict do nothing;

insert into blocks (blocker_id, blocked_id)
select user_id, contact_user_id
from contacts
where status = 'BLOCKED'
  and user_id is not null
  and contact_user_id is not null
  and user_id <> contact_user_id
on conflict do nothing;

-- mutual likes become matches, unless one of them blocked the other
insert into matches (user_low_id, user_high_id, status)
select a.from_user_id, a.to_user_id, 'ACTIVE'
from reactions a
         join reactions b on b.from_user_id = a.to_user_id and b.to_user_id = a.from_user_id
where a.type = 'LIKE'
  and b.type = 'LIKE'
  and a.from_user_id < a.to_user_id
  and not exists (select 1
                  from blocks x
                  where (x.blocker_id = a.from_user_id and x.blocked_id = a.to_user_id)
                     or (x.blocker_id = a.to_user_id and x.blocked_id = a.from_user_id));

drop table contacts;
