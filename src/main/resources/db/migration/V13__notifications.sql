-- Notifications about new likes and matches, written from Kafka events. Kafka delivers at least once, so
-- source_key makes the write idempotent per user (e.g. 'like:<actor>' or 'match:<match>').
create table notifications
(
    id                 bigint generated by default as identity primary key,
    reference_id       varchar(36)  not null unique,
    user_id            bigint       not null references users (id) on delete cascade,
    type               varchar(30)  not null,
    -- the person the notification is about; deleted with them
    actor_id           bigint       references users (id) on delete cascade,
    reaction_type      varchar(30),
    match_reference_id varchar(36),
    source_key         varchar(100) not null,
    created_at         timestamptz  not null default now(),
    read_at            timestamptz,
    unique (user_id, source_key)
);

create index ix_notifications_user on notifications (user_id, id desc);
create index ix_notifications_unread on notifications (user_id) where read_at is null;
