-- Fixed catalog of interests and hobbies. Users reference tags by slug, so matching works on normalized values.
-- New tags are added with a new migration (or later via an admin endpoint).
create table tags
(
    id       bigint generated by default as identity primary key,
    category varchar(20)  not null,
    slug     varchar(64)  not null,
    label    varchar(128) not null,
    unique (category, slug)
);

