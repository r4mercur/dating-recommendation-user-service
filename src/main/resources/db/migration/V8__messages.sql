-- Phase 4: a conversation is the match itself; messages belong to a match and disappear with it.

create table messages
(
    id           bigint generated by default as identity primary key,
    reference_id varchar(36)   not null unique,
    match_id     bigint        not null references matches (id) on delete cascade,
    sender_id    bigint        not null references users (id) on delete cascade,
    content      varchar(2000) not null,
    created_at   timestamptz   not null default now(),
    read_at      timestamptz
);

-- history pages (newest first) and unread counters
create index ix_messages_match_id on messages (match_id, id desc);
create index ix_messages_unread on messages (match_id, sender_id) where read_at is null;

-- sort the conversation list without scanning messages
alter table matches add column last_message_at timestamptz;
