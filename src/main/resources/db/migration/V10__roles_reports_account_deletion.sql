-- Phase 5 security: roles for moderation, user reports and real account deletion.

-- USER or ADMIN; the first admins come from app.security.admin-emails
alter table users add column role varchar(20) not null default 'USER';

-- set when the user asks for deletion; the purge job deletes the account after the grace period
alter table users add column deletion_requested_at timestamptz;
update users set deletion_requested_at = now() where status = 'MARKED_FOR_DELETION';

create table reports
(
    id              bigint generated by default as identity primary key,
    reference_id    varchar(36)   not null unique default gen_random_uuid()::text,
    -- the reporter may delete their account later; the report stays for moderation
    reporter_id     bigint references users (id) on delete set null,
    reported_id     bigint        not null references users (id) on delete cascade,
    reason          varchar(30)   not null,
    comment         varchar(1000),
    status          varchar(20)   not null,
    created_at      timestamptz   not null default now(),
    resolved_at     timestamptz,
    resolved_by_id  bigint references users (id) on delete set null,
    resolution_note varchar(1000)
);

-- one open report per reporter and reported user
create unique index ux_reports_open_pair on reports (reporter_id, reported_id) where status = 'OPEN';
create index ix_reports_status_created on reports (status, created_at);
create index ix_reports_reported on reports (reported_id);
