-- Offline geocoding table (postal code -> coordinates). Filled on application start by PostalCodeImporter.
create table postal_codes
(
    id           bigint generated by default as identity primary key,
    country_code varchar(2)       not null,
    postal_code  varchar(10)      not null,
    place_name   varchar(200)     not null,
    state        varchar(100),
    latitude     double precision not null,
    longitude    double precision not null
);

create index ix_postal_codes_country_postal_code on postal_codes (country_code, postal_code);
create index ix_postal_codes_country_place_name on postal_codes (country_code, upper(place_name));
