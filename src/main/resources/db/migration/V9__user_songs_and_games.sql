-- Music and favourite games in the profile. Songs and games are copies of the external data (Spotify, IGDB), chosen
-- by the user: showing a profile never calls an external API.

create table user_songs
(
    id               bigint generated by default as identity primary key,
    user_id          bigint        not null references users (id) on delete cascade,
    position         integer       not null,
    spotify_track_id varchar(32)   not null,
    name             varchar(255)  not null,
    artists          varchar(255)[] not null,
    album            varchar(255),
    image_url        varchar(512),
    anthem           boolean       not null default false,
    constraint ux_user_songs_position unique (user_id, position),
    constraint ux_user_songs_track unique (user_id, spotify_track_id)
);

-- at most one profile song per user
create unique index ux_user_songs_anthem on user_songs (user_id) where anthem;

create table user_games
(
    id           bigint generated by default as identity primary key,
    user_id      bigint        not null references users (id) on delete cascade,
    position     integer       not null,
    igdb_id      bigint        not null,
    name         varchar(255)  not null,
    cover_url    varchar(512),
    year         integer,
    platforms    varchar(255)[] not null,
    steam_app_id bigint,
    constraint ux_user_games_position unique (user_id, position),
    constraint ux_user_games_game unique (user_id, igdb_id)
);
