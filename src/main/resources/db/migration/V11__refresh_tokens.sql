-- Refresh tokens with rotation. Only a SHA-256 hash of the token is stored. All tokens issued from one login form
-- a family; reusing an already rotated token revokes the whole family (the token was probably stolen).
create table refresh_tokens
(
    id         bigint generated by default as identity primary key,
    user_id    bigint      not null references users (id) on delete cascade,
    token_hash varchar(64) not null unique,
    family_id  varchar(36) not null,
    created_at timestamptz not null default now(),
    expires_at timestamptz not null,
    -- set when the token was exchanged for a new one
    used_at    timestamptz,
    revoked_at timestamptz
);

create index ix_refresh_tokens_family on refresh_tokens (family_id);
create index ix_refresh_tokens_user on refresh_tokens (user_id);
create index ix_refresh_tokens_expires on refresh_tokens (expires_at);
